# the first test. If given, it runs before each test while Blaze is stopped, so
# that every test starts with the same database and purges the same Patients.
# Its absolute path, because a relative one without a slash would be looked up
# in the PATH.
reset_script=""
if [[ -n "${3:-}" ]]; then
  if ! [[ -f "$3" && -x "$3" ]]; then
    echo "🆘 the reset script has to be an executable file but was: $3" >&2
    exit 1
