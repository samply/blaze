# Returns the id of the Patient with the Synthea identifier or nothing if no
# such Patient exists, because an earlier run purged it.
patient-id() {
  local identifier="$1"
  curl -sSf -H "Accept: application/fhir+json" --get "$base/Patient" \
    --data-urlencode "identifier=https://github.com/synthetichealth/synthea|$identifier" \
    --data-urlencode "_elements=id" |
    jq -r '.entry[0].resource.id // empty'
}

# Prints the id and the number of resources of the first candidate Patients
# that exist, which are the ones not purged by an earlier run, one per line.
# Stops after the needed number, so that not all candidates are looked up.
existing-patients() {
  local needed="$1"
  shift

  local patient identifier count id found=0
  for patient in "$@"; do
    read -r identifier count <<< "$patient"
    id="$(patient-id "$identifier")"
    if [[ -n "$id" ]]; then
      echo "$id $count"
      found=$((found + 1))
      if ((found == needed)); then
        return
      fi
    fi
  done
}

# Purges the Patient and appends the duration to the times file.
purge-patient() {
  local patient_id="$1"
  local times_file="$2"
  local response_file
  response_file="$(mktemp)"

  curl -sSf -H "Accept: application/fhir+json" -X POST "$base/Patient/$patient_id/\$purge" -o "$response_file" -w '%{time_total}\n' >> "$times_file"

  local code
  code="$(jq -r '.issue[0].code' "$response_file")"
  rm "$response_file"
  if [ "$code" != "success" ]; then
    echo "🆘 the purge of Patient $patient_id failed with code $code"
    exit 1
  fi
}

purge_graph="https://blaze-server.org/fhir/GraphDefinition/PatientPurge"

# Updates all resources the purge of the Patient removes, found with the $graph
# operation, so that each of them gets a second version. Sets the language,
# which all resource types have and the Synthea resources don't, because an
# update that doesn't change the content of a resource creates no version.
# Updates all resources of the Patient in a single transaction.
update-resources() {
  local patient_id="$1"

  curl -sSf -H "Accept: application/fhir+json" "$base/Patient/$patient_id/\$graph?graph=$purge_graph" |
    jq -c '{resourceType: "Bundle", type: "transaction",
      entry: [.entry[].resource | {
        resource: (. + {language: "de"}),
        request: {method: "PUT", url: "\(.resourceType)/\(.id)"}}]}' |
    curl -sSf -H "Accept: application/fhir+json" \
      -H "Content-Type: application/fhir+json" -H "Prefer: return=minimal" \
      --data-binary @- -o /dev/null "$base"
}

# Updates the resources of the Patients given as arguments, each in the format
# `existing-patients` prints, `update_parallelism` of them at the same time.
# Starts the update of the next Patient once the oldest one still running is
# done, and fails if an update fails.
update-all-resources() {
  local patient pid pids=()
  for patient in "$@"; do
    if ((${#pids[@]} == update_parallelism)); then
      wait "${pids[0]}"
      pids=("${pids[@]:1}")
    fi
    update-resources "${patient%% *}" &
    pids+=("$!")
  done

  for pid in "${pids[@]}"; do
    wait "$pid"
  done
}

# Purges REPEATS + warmups of the candidate Patients given as arguments after
# the size, like `large`, which names them in the output, and whether their
# resources are the `original` ones of the dataset, with one version each, or
# `updated` before, with two versions each. The first `warmups` purges are the
# warmup. Each candidate is in the format of the lists above.
purge-patients() {
  local size="$1"
  local resources="$2"
  shift 2

  local repeats
  repeats="$(repeats "$default_repeats")"
  local needed=$((warmups + repeats))

  # the Patients are looked up before the first purge, so that a run without
  # enough of them fails before purging any and the lookups aren't profiled
  local existing patient patients=()
  existing="$(existing-patients "$needed" "$@")"
  while read -r patient; do
    if [[ -n "$patient" ]]; then
      patients+=("$patient")
    fi
  done <<< "$existing"

  if ((${#patients[@]} < needed)); then
    echo "🆘 REPEATS=$repeats needs $needed candidate Patients, $warmups for the warmup and one for each repeat, but only ${#patients[@]} exist, please lower REPEATS, reset the database or reimport the dataset" >&2
    exit 1
  fi

  # the resources are updated before the first purge as well, so that the
  # updates aren't profiled, and Blaze is restarted afterwards, so that the
  # purges start with empty caches like the ones of the original resources
  if [[ "$resources" == "updated" ]]; then
    echo "Updating the resources of ${#patients[@]} $size Patients..."
    update-all-resources "${patients[@]}"
    recreate "$compose_file"
  fi

  local times_file
  times_file="$(mktemp)"

  echo "Purging $size Patients with $resources resources..."

  # the first runs are the warmup which isn't taken for the statistics, so their
  # resources aren't counted
  local i patient_id count total_count=0
  for ((i = 0; i < needed; i++)); do
    read -r patient_id count <<< "${patients[i]}"
    if ((i >= warmups)); then
      total_count=$((total_count + count))
    fi

    purge-patient "$patient_id" "$times_file"
    start-profiling-after-warmup "$i" "$warmups"
  done

  # the average count, so that the resources per second relate to all purges,
  # and three decimal digits, because a purge takes only a few hundredths of a
  # second
  calc-print-stats "$times_file" "$((total_count / repeats))" "$warmups" 3
  rm "$times_file"
}

# Restarts Blaze before the next test, resetting its database with the reset
# script first, if one is given.
restart-before-test() {
  if [[ -n "$reset_script" ]]; then
    reset-and-restart "$compose_file" "$reset_script"
  else
    restart "$compose_file"
  fi
}

